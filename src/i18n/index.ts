const messages: Record<AppLocale, Record<string, string>> = { 'pt-BR': ptBR, en }
const locale = ref<AppLocale>('pt-BR')
let initialized = false

export function isAppLocale(value: unknown): value is AppLocale {
  return value === 'pt-BR' || value === 'en'
}

function browserLocale(): AppLocale {
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en'
}

function applyLocale(): void {
  document.documentElement.lang = locale.value
  document.querySelector('meta[name="description"]')?.setAttribute(
    'content',
    messages[locale.value]['meta.description'] ?? ptBR['meta.description'],
  )
}

export function initializeLocale(): void {
  if (initialized || typeof window === 'undefined') return

  try {
    const storedLocale = window.localStorage.getItem(STORAGE_KEY)
    locale.value = isAppLocale(storedLocale) ? storedLocale : browserLocale()
  } catch {
    locale.value = browserLocale()
  }

  applyLocale()
  initialized = true
}

export function setLocale(value: AppLocale): void {
  locale.value = value
  applyLocale()

  try {
    window.localStorage.setItem(STORAGE_KEY, value)
  } catch {
    // A troca continua válida durante a sessão quando o armazenamento está indisponível.
  }
}

export function translate(key: string, parameters: MessageParameters = {}): string {
  const template = messages[locale.value][key] ?? ptBR[key] ?? key
  return Object.entries(parameters).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  )
}

export function useI18n() {
  initializeLocale()

  return {
    locale: readonly(locale),
    localeCode: computed(() => locale.value),
    t: translate,
    setLocale,
  }
}

export { locale }
